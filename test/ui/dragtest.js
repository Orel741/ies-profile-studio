module.exports = async (page, name) => {
  if (name !== 'desk-dark') return;
  const fx = () => page.$$eval('#layerList li.lyr', ls => ls.map(l => l.querySelector('.lname .n').textContent + (l.classList.contains('sel') ? '*' : '') + ' [' + [...l.querySelectorAll('.fxname')].map(f => f.textContent.split(' ')[0]).join(',') + ']').join(' / '));
  const mods = () => page.$$eval('#modList .mhead strong', e => e.map(x => x.textContent).join(','));
  const drag = async (sel, dy) => { const b = await (await page.$(sel)).boundingBox(); await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2); await page.mouse.down(); await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2 + dy, { steps: 10 }); await page.mouse.up(); await page.waitForTimeout(200); };
  await page.selectOption('#modAdd', 'noise'); await page.selectOption('#modAdd', 'rays'); await page.selectOption('#modAdd', 'cut');
  await page.selectOption('#layerAdd', 'curve'); await page.selectOption('#layerCurve', 'p:ell'); await page.waitForTimeout(100);
  await page.selectOption('#layerAdd', 'curve'); await page.selectOption('#layerCurve', 'p:ell'); await page.waitForTimeout(150);
  console.log('start:', await fx());
  await drag('#layerList > li:nth-child(1) .lname', 140);
  console.log('top layer dragged down 2:', await fx());
  await drag('#layerList > li:nth-child(3) .fx:nth-child(1) .fxname', 46);
  console.log('noise dragged below rays:', await fx(), '| flux', await page.$eval('#rdFlux', e => e.textContent));
  await page.click('#layerList > li:nth-child(3) .lname'); await page.waitForTimeout(150);
  console.log('selected base, mods panel:', await mods());
  const h = await (await page.$('#modList .mod:nth-child(3)')).boundingBox();
  await page.$eval('#modList', e => e.scrollIntoView({ block: 'center' })); await page.waitForTimeout(100);
  await drag('#modList .mod:nth-child(3) .mhead strong', -2.2 * h.height);
  console.log('cut dragged to top in panel:', await mods(), '|', await fx());
  await page.click('#btnUndo'); await page.waitForTimeout(150);
  console.log('undo:', await mods());
  await page.focus('#layerList > li:nth-child(1) .lrow .grip'); await page.keyboard.press('ArrowDown'); await page.waitForTimeout(150);
  console.log('key down on top grip:', await fx(), '| focus', await page.evaluate(() => document.activeElement.getAttribute('aria-label')));
  await page.evaluate(() => window.scrollTo(0, 0)); await page.waitForTimeout(200);
  const c = await (await page.$('#layersCard')).boundingBox();
  await page.screenshot({ path: 'test/shots/DRAG.png', clip: { x: c.x, y: c.y, width: c.width, height: 330 } });
  const m = await (await page.$('#modList')).boundingBox();
  await page.screenshot({ path: 'test/shots/DRAGmods.png', clip: { x: m.x - 10, y: m.y - 10, width: m.width + 20, height: 200 } });
};
